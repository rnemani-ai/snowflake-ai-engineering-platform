-- 4. VERIFICATION
-- ============================================================================

-- Verify table creation
SELECT TABLE_NAME, ROW_COUNT 
FROM BANKING_DQ_DB.INFORMATION_SCHEMA.TABLES 
WHERE TABLE_SCHEMA = 'DQ_MONITORING' 
ORDER BY TABLE_NAME;

-- Verify rule loading summary
SELECT TABLE_NM, CRITICALITY, COUNT(*) AS RULE_COUNT 
FROM BANKING_DQ_DB.DQ_MONITORING.DQ_RULE_CONFIG 
WHERE IS_ACTIVE = TRUE 
GROUP BY TABLE_NM, CRITICALITY 
ORDER BY TABLE_NM, CRITICALITY;

-- Verify rule type distribution
SELECT RULE_TYPE, COUNT(*) AS CNT 
FROM BANKING_DQ_DB.DQ_MONITORING.DQ_RULE_CONFIG 
GROUP BY RULE_TYPE 
ORDER BY CNT DESC;

