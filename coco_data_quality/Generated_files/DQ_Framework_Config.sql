-- ============================================================================
-- 1. CREATE SCHEMA
-- ============================================================================

CREATE SCHEMA IF NOT EXISTS BANKING_DQ_DB.DQ_MONITORING;
USE DATABASE BANKING_DQ_DB;
USE SCHEMA DQ_MONITORING;

-- ============================================================================
-- 2. CREATE FRAMEWORK TABLES
-- ============================================================================

-- 2a. DQ_RULE_CONFIG — Store all data quality rules
CREATE OR REPLACE TABLE BANKING_DQ_DB.DQ_MONITORING.DQ_RULE_CONFIG (
    RULE_ID         NUMBER          NOT NULL,
    RULE_NAME       VARCHAR(200)    NOT NULL,
    RULE_TYPE       VARCHAR(50)     NOT NULL,
    FREQUENCY       VARCHAR(50)     DEFAULT 'ON_DEMAND',
    CRITICALITY     VARCHAR(20)     NOT NULL,
    DB_NAME         VARCHAR(200),
    TABLE_NM        VARCHAR(200),
    COLUMN_NM       VARCHAR(200),
    RULE_DESCRIPTION VARCHAR(1000),
    RULE_SQL        VARCHAR(5000)   NOT NULL,
    THRESHOLD_VALUE NUMBER(18,4)    DEFAULT 0,
    RULE_DIMENSION  VARCHAR(500),
    IS_ACTIVE       BOOLEAN         DEFAULT TRUE,
    CREATED_AT      TIMESTAMP_NTZ   DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT      TIMESTAMP_NTZ   DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DQ_RULE_CONFIG PRIMARY KEY (RULE_ID)
);

-- 2b. DQ_RUN_CONTROL — Track each execution run
CREATE OR REPLACE TABLE BANKING_DQ_DB.DQ_MONITORING.DQ_RUN_CONTROL (
    RUN_ID              NUMBER          NOT NULL AUTOINCREMENT START 1 INCREMENT 1,
    RULE_ID             NUMBER          NOT NULL,
    RUN_START_TIME      TIMESTAMP_NTZ,
    RUN_END_TIME        TIMESTAMP_NTZ,
    RULE_EXEC_RESULT    VARCHAR(20),
    RULE_OUTPUT_VALUE   NUMBER(18,4),
    RUN_STATUS          VARCHAR(20)     DEFAULT 'PENDING',
    TRIGGERED_BY        VARCHAR(100)    DEFAULT 'MANUAL',
    ERROR_MESSAGE       VARCHAR(2000),
    CREATED_AT          TIMESTAMP_NTZ   DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT          TIMESTAMP_NTZ   DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DQ_RUN_CONTROL PRIMARY KEY (RUN_ID)
);

-- 2c. DQ_RULE_RESULTS — Store rule-level execution results
CREATE OR REPLACE TABLE BANKING_DQ_DB.DQ_MONITORING.DQ_RULE_RESULTS (
    RESULT_ID           NUMBER          NOT NULL AUTOINCREMENT START 1 INCREMENT 1,
    RUN_ID              NUMBER          NOT NULL,
    RULE_ID             NUMBER          NOT NULL,
    DB_NAME             VARCHAR(200),
    TABLE_NAME          VARCHAR(200),
    COLUMN_NAME         VARCHAR(200),
    RULE_NAME           VARCHAR(200),
    RULE_TYPE           VARCHAR(50),
    EXPECTED_VALUE      NUMBER(18,4),
    ACTUAL_VALUE        NUMBER(18,4),
    FAILED_RECORD_COUNT NUMBER(18,0),
    TOTAL_RECORD_COUNT  NUMBER(18,0),
    PASS_PERCENTAGE     NUMBER(7,4),
    RESULT_STATUS       VARCHAR(20),
    SEVERITY            VARCHAR(20),
    ERROR_SAMPLE_QUERY  VARCHAR(5000),
    EXECUTED_AT         TIMESTAMP_NTZ   DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DQ_RULE_RESULTS PRIMARY KEY (RESULT_ID)
);

-- 2d. DQ_ERROR_RECORDS — Store detailed failed records or samples
CREATE OR REPLACE TABLE BANKING_DQ_DB.DQ_MONITORING.DQ_ERROR_RECORDS (
    ERROR_ID            NUMBER          NOT NULL AUTOINCREMENT START 1 INCREMENT 1,
    RUN_ID              NUMBER          NOT NULL,
    RULE_ID             NUMBER          NOT NULL,
    DB_NAME             VARCHAR(200),
    TABLE_NAME          VARCHAR(200),
    ERROR_RECORD_VARIANT VARIANT,
    ERROR_REASON        VARCHAR(1000),
    CREATED_AT          TIMESTAMP_NTZ   DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DQ_ERROR_RECORDS PRIMARY KEY (ERROR_ID)
);

-- 2e. DQ_ANOMALY_RESULTS — Store anomaly detection results
CREATE OR REPLACE TABLE BANKING_DQ_DB.DQ_MONITORING.DQ_ANOMALY_RESULTS (
    ANOMALY_ID          NUMBER          NOT NULL AUTOINCREMENT START 1 INCREMENT 1,
    RUN_ID              NUMBER          NOT NULL,
    DATABASE_NAME       VARCHAR(200),
    SCHEMA_NAME         VARCHAR(200),
    TABLE_NAME          VARCHAR(200),
    METRIC_NAME         VARCHAR(200),
    CURRENT_VALUE       NUMBER(18,4),
    PREVIOUS_VALUE      NUMBER(18,4),
    BASELINE_AVG        NUMBER(18,4),
    BASELINE_STDDEV     NUMBER(18,4),
    ANOMALY_STATUS      VARCHAR(50),
    ANOMALY_REASON      VARCHAR(1000),
    DETECTED_AT         TIMESTAMP_NTZ   DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DQ_ANOMALY_RESULTS PRIMARY KEY (ANOMALY_ID)
);

